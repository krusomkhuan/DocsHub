- ข้อมูลบัญชีผู้ใช้: ตลอดระยะเวลาที่ท่านเป็นบุคลากรของวิทยาลัย หรือจนกว่าจะมีคำขอลบข้อมูลที่ได้รับอนุมัติ
- ประวัติการใช้งานระบบ: {log_retention_days} วัน แล้วลบอัตโนมัติ
- เอกสารราชการ: ตามระเบียบสำนักนายกรัฐมนตรีว่าด้วยงานสารบรรณ

## 6. สิทธิของเจ้าของข้อมูลส่วนบุคคล
ท่านมีสิทธิขอเข้าถึงและขอรับสำเนาข้อมูล ขอให้แก้ไขข้อมูลให้ถูกต้อง ขอให้ลบหรือทำให้ข้อมูลไม่สามารถระบุตัวตนได้ ขอให้ระงับการใช้ คัดค้านการประมวลผล ขอรับข้อมูลในรูปแบบที่อ่านได้ด้วยเครื่อง และถอนความยินยอม ท่านใช้สิทธิได้ที่เมนู "ข้อมูลส่วนบุคคลของฉัน" หลังเข้าสู่ระบบ หรือติดต่อเจ้าหน้าที่คุ้มครองข้อมูลส่วนบุคคล วิทยาลัยจะดำเนินการภายใน 30 วันนับแต่ได้รับคำขอ และท่านมีสิทธิร้องเรียนต่อสำนักงานคณะกรรมการคุ้มครองข้อมูลส่วนบุคคล

