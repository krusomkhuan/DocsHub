- กรณีเข้าสู่ระบบด้วย Google: ชื่อ อีเมล และรหัสบัญชี Google ที่ Google ส่งมาเพื่อยืนยันตัวตน (ระบบไม่ได้รับรหัสผ่าน Google)
- ภาพโปรไฟล์ (ถ้าอัปโหลด)
- ข้อมูลในเอกสารที่อัปโหลด เช่น ชื่อผู้รับเกียรติบัตร ผู้สอน ผู้ไปราชการ และภาพประกอบรายงานการไปราชการ
- ข้อมูลบัญชีรายรับ-รายจ่ายของแผนกวิชา ซึ่งอาจมีชื่อผู้รับเงินหรือผู้จ่ายเงิน
- ข้อมูลการใช้งานระบบ: วันเวลาเข้าสู่ระบบ ประวัติการทำรายการ และหมายเลข IP
- คุกกี้ที่จำเป็นต่อการทำงานของระบบ (คุกกี้เซสชันสำหรับการเข้าสู่ระบบ) ระบบไม่ใช้คุกกี้เพื่อการโฆษณาหรือติดตามพฤติกรรม

## 2. วัตถุประสงค์ในการใช้ข้อมูล
- เพื่อยืนยันตัวตนและให้บริการจัดเก็บ ค้นหา และเผยแพร่เอกสารของวิทยาลัย
- เพื่อออกเลขหนังสือราชการ จัดทำรายงานการไปราชการ และบัญชีรายรับ-รายจ่ายของแผนกวิชา
- เพื่อติดต่อประสานงานภายในวิทยาลัย
- เพื่อรักษาความปลอดภัยของระบบ ตรวจสอบย้อนหลัง และป้องกันการใช้งานโดยมิชอบ

## 3. ฐานทางกฎหมาย
- การปฏิบัติหน้าที่ในการดำเนินภารกิจเพื่อประโยชน์สาธารณะ และการใช้อำนาจรัฐของสถานศึกษา
- การปฏิบัติตามกฎหมายและระเบียบงานสารบรรณ
- ประโยชน์โดยชอบด้วยกฎหมายในการรักษาความปลอดภัยของระบบ
- ความยินยอมของท่าน สำหรับข้อมูลที่ท่านเลือกให้เพิ่มเติม เช่น ภาพโปรไฟล์ อีเมล และเบอร์โทรศัพท์

## 4. การเปิดเผยข้อมูล
- ข้อมูลบัญชีผู้ใช้เปิดเผยเฉพาะผู้ดูแลระบบและเจ้าหน้าที่ที่ได้รับมอบหมาย
- เอกสารที่ตั้งค่าเป็น "สาธารณะ" จะเปิดเผยต่อบุคคลทั่วไป ผู้อัปโหลดมีหน้าที่ตรวจสอบว่าเอกสารไม่มีข้อมูลส่วนบุคคลเกินความจำเป็น
- บัญชีรายรับ-รายจ่ายของแผนกวิชาเปิดเผยเฉพาะครูที่สังกัดแผนกวิชานั้นเท่านั้น
- วิทยาลัยไม่ขายหรือส่งต่อข้อมูลส่วนบุคคลให้บุคคลภายนอก เว้นแต่กฎหมายกำหนด

