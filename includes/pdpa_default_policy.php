## 1. ข้อมูลส่วนบุคคลที่เก็บรวบรวม
- ข้อมูลบัญชีผู้ใช้: ชื่อผู้ใช้ ชื่อ-สกุล แผนกวิชา/ฝ่าย บทบาทในระบบ และรหัสผ่าน (จัดเก็บในรูปแบบเข้ารหัสทางเดียว ไม่มีผู้ใดเห็นรหัสผ่านจริง)
